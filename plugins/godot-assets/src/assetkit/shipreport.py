"""Which shipped assets are AI-generated, and from what: the answer a store disclosure needs."""

from __future__ import annotations

import logging
from collections.abc import Mapping
from dataclasses import dataclass

from assetkit.contracts import Json
from assetkit.registry import AssetRecords, Registry
from assetkit.status import Status, fold

log = logging.getLogger(__name__)

# IPTC digital source types made with generative AI (cv.iptc.org/newscodes/digitalsourcetype,
# read 2026-11-14). "composite" only may hold AI; a disclosure counts it rather than miss one.
AI_SOURCE_TYPES = frozenset(
    {
        "trainedAlgorithmicMedia",
        "compositeWithTrainedAlgorithmicMedia",
        "compositeSynthetic",
        "virtualRecording",
        "composite",
    }
)
NOT_SHIPPED = frozenset({Status.REJECTED, Status.DEPRECATED})


@dataclass(frozen=True)
class ShippedAsset:
    asset: str
    title: str
    status: Status
    version: str | None
    res_path: str | None
    provenance: Mapping[str, Json]
    generation: Mapping[str, Json] | None
    ai_reason: str | None

    def as_json(self) -> dict[str, Json]:
        return {
            "asset": self.asset,
            "title": self.title,
            "status": str(self.status),
            "version": self.version,
            "res_path": self.res_path,
            "ai_generated": self.ai_reason is not None,
            "ai_reason": self.ai_reason,
            "provenance": dict(self.provenance),
            "generation": dict(self.generation) if self.generation else None,
        }


def ship_report(registry: Registry) -> list[ShippedAsset]:
    shipped = []
    for records in registry.records():
        if not records.asset.get("ship"):
            continue
        entry = _entry(records)
        if entry.status in NOT_SHIPPED:
            log.info("%s is %s: left out of the ship report", entry.asset, entry.status)
            continue
        shipped.append(entry)
    return shipped


def _entry(records: AssetRecords) -> ShippedAsset:
    folded = fold(records.versions, records.events)
    promotions = [event for event in records.events if event["type"] == "promote"]
    # What is in the game is the last promoted version; before promotion, the current one.
    version_id = str(promotions[-1]["version_id"]) if promotions else folded.current_version
    res_path = str(promotions[-1]["promote"]["res_path"]) if promotions else None
    versions = {str(v["id"]): v for v in records.versions}
    version = versions.get(version_id) if version_id else None
    return ShippedAsset(
        asset=str(records.asset["id"]),
        title=str(records.asset["title"]),
        status=folded.status,
        version=version_id,
        res_path=res_path,
        provenance=version["provenance"] if version else {},
        generation=version.get("generation") if version else None,
        ai_reason=_ai_reason(version_id, versions),
    )


def _ai_reason(version_id: str | None, versions: Mapping[str, Mapping[str, Json]]) -> str | None:
    """Why a version counts as AI-made, parents included: an edited generated file still is."""
    first, seen = version_id, set[str]()
    while version_id is not None and version_id in versions and version_id not in seen:
        seen.add(version_id)
        version = versions[version_id]
        provenance = version["provenance"]
        own = "" if version_id == first else f" (in parent version {version_id})"
        if provenance["origin"] == "generated":
            model = version["generation"]
            return f"origin generated by {model['provider']}/{model['model']}{own}"
        source_type = provenance.get("digital_source_type")
        if source_type in AI_SOURCE_TYPES:
            return f"digital_source_type {source_type}{own}"
        parent = version.get("parent_version")
        version_id = str(parent) if parent else None
    return None
