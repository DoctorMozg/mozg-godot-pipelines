"""Ship report: which shipped assets are AI-generated, through parents and source types."""

from __future__ import annotations

import pytest
from assetkit.registry import Registry
from assetkit.shipreport import ship_report
from assetkit_rig import HUMAN, CliRunner, Lane

GENERATED = {"origin": "generated", "license": "LicenseRef-fal"}
MODEL = {"provider": "fal", "model": "nano-banana-pro"}


def _reasons(registry: Registry) -> dict[str, str | None]:
    return {entry.title: entry.ai_reason for entry in ship_report(registry)}


def test_generated_and_human_assets_are_told_apart(registry: Registry) -> None:
    human, made = Lane(registry, "Hand", ship=True), Lane(registry, "Made", ship=True)
    human.version(b"hand")
    made.version(b"made", GENERATED, MODEL)
    Lane(registry, "Not shipped").version(b"other", GENERATED, MODEL)
    assert _reasons(registry) == {
        "Hand": None,
        "Made": "origin generated by fal/nano-banana-pro",
    }


def test_human_edit_of_a_generated_parent_still_counts(registry: Registry) -> None:
    lane = Lane(registry, "Edited", ship=True)
    first = lane.version(b"draft", GENERATED, MODEL)
    lane.version(b"retouched", {**HUMAN, "human_edited": True}, parent=first)
    [reason] = _reasons(registry).values()
    assert reason == f"origin generated by fal/nano-banana-pro (in parent version {first})"


@pytest.mark.parametrize(
    ("source_type", "counted"),
    [("compositeSynthetic", True), ("composite", True), ("digitalCreation", False)],
)
def test_iptc_source_type_marks_ai(registry: Registry, source_type: str, counted: bool) -> None:
    Lane(registry, "Typed", ship=True).version(
        b"typed", {**HUMAN, "digital_source_type": source_type}
    )
    assert (_reasons(registry)["Typed"] is not None) is counted


def test_the_promoted_version_is_what_ships(registry: Registry) -> None:
    lane = Lane(registry, "Play", ship=True)
    lane.approve(lane.version(b"one"))
    lane.promote()
    newer = lane.version(b"generated", GENERATED, MODEL)
    [entry] = ship_report(registry)
    assert (entry.res_path, entry.ai_reason) == ("res://ui/play.png", None)
    assert entry.version != newer


def test_rejected_assets_are_left_out(registry: Registry) -> None:
    lane = Lane(registry, "Dropped", ship=True)
    version = lane.version(b"x", GENERATED, MODEL)
    fields = {"type": "decision", "decision": "reject", "version_id": version, "author": "t"}
    registry.add_event(lane.asset, fields)
    assert ship_report(registry) == []


def test_cli_lists_only_ai_assets_on_request(run_cli: CliRunner) -> None:
    for title, origin in (("Hand", "human"), ("Made", "generated")):
        _, payload = run_cli("new", "--family", "ui", "--kind", "image", "--title", title, "--ship")
        extra = ("--provider", "fal", "--model", "m") if origin == "generated" else ()
        add = ("version", "add", payload["asset"]["id"], "--file", "art/hero.png")
        assert run_cli(*add, "--origin", origin, "--license", "MIT", *extra)[0] == 0
    code, payload = run_cli("ship-report", "--ai-only")
    assert (code, payload["shipped"], payload["ai_generated"]) == (0, 2, 1)
    assert [a["title"] for a in payload["assets"]] == ["Made"]
