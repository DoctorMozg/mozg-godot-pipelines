"""Behavior of the commit-message guard that enforces the owner's git rules."""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path

import check_commit_msg as guard
import pytest

WriteMessage = Callable[[str], Path]


@pytest.fixture
def write_message(tmp_path: Path) -> WriteMessage:
    def write(text: str) -> Path:
        path = tmp_path / "COMMIT_EDITMSG"
        path.write_text(text, encoding="utf-8")
        return path

    return write


class TestWordLimit:
    @pytest.mark.parametrize(
        "message",
        ["Add repo docs", "Add repo docs and review queue\n", "Добавить тесты для хука"],
    )
    def test_accepts_up_to_six_words(self, message: str) -> None:
        assert guard.violations(message) == []

    def test_rejects_seven_words(self) -> None:
        problems = guard.violations("Add repo docs and the review queue")
        assert problems == ["message has 7 words, the limit is 6"]

    def test_repeated_spaces_do_not_inflate_the_count(self) -> None:
        assert guard.violations("Add   repo    docs   and   review   queue") == []

    def test_hyphenated_word_counts_once(self) -> None:
        assert guard.violations("Add pre-commit hook to repo now") == []


class TestShape:
    @pytest.mark.parametrize("message", ["", "   \n\t\n", "# only a comment\n# another\n"])
    def test_empty_message_is_rejected(self, message: str) -> None:
        assert guard.violations(message) == ["commit message is empty"]

    def test_body_is_rejected(self) -> None:
        problems = guard.violations("Add repo docs\n\nLonger explanation of why.")
        assert "message must be one line, found 2 lines" in problems

    def test_template_comment_lines_are_ignored(self) -> None:
        assert guard.violations("Add repo docs\n# Please enter the commit message\n") == []

    def test_crlf_line_endings_are_accepted(self) -> None:
        assert guard.violations("Add repo docs\r\n") == []

    def test_non_string_input_is_a_programming_error(self) -> None:
        with pytest.raises(TypeError, match="message must be str"):
            guard.violations(None)  # type: ignore[arg-type]


class TestAttribution:
    @pytest.mark.parametrize(
        "trailer",
        [
            "Co-Authored-By: Claude <noreply@anthropic.com>",
            "co-authored-by: someone",
            "Generated with Claude Code",
            "generated by a tool",
            "Sent from \U0001f916",
            "noreply@anthropic.com",
        ],
    )
    def test_trailer_is_rejected(self, trailer: str) -> None:
        problems = guard.violations(f"Add repo docs\n\n{trailer}")
        assert "message carries an AI attribution line, which is never allowed" in problems

    def test_attribution_in_a_comment_line_is_ignored(self) -> None:
        assert guard.violations("Add repo docs\n# Co-Authored-By: template text\n") == []

    def test_one_line_message_with_attribution_reports_only_that(self) -> None:
        problems = guard.violations("Co-Authored-By: x")
        assert problems == ["message carries an AI attribution line, which is never allowed"]


class TestHookEntrypoint:
    def test_accepted_message_exits_zero_and_stays_silent(
        self, write_message: WriteMessage, capsys: pytest.CaptureFixture[str]
    ) -> None:
        assert guard.main([str(write_message("Add repo docs"))]) == 0
        assert capsys.readouterr().err == ""

    def test_rejected_message_exits_one_and_explains_why(
        self, write_message: WriteMessage, capsys: pytest.CaptureFixture[str]
    ) -> None:
        path = write_message("one two three four five six seven")
        assert guard.main([str(path)]) == 1
        assert "has 7 words" in capsys.readouterr().err

    def test_missing_file_is_a_usage_error_not_a_pass(
        self, tmp_path: Path, capsys: pytest.CaptureFixture[str]
    ) -> None:
        assert guard.main([str(tmp_path / "absent")]) == 2
        assert "cannot read commit message file" in capsys.readouterr().err

    @pytest.mark.parametrize("args", [[], ["a", "b"]])
    def test_wrong_argument_count_is_a_usage_error(self, args: list[str]) -> None:
        assert guard.main(args) == 2
